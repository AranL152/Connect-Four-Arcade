// Game logic (fully functional)

int is_valid_col(int col) {
    return (col >= 0 && col < COLS && board[0][col] == EMPTY);
}

int get_open_row(int col) {
    int r;
    for (r = ROWS - 1; r >= 0; r--)
        if (board[r][col] == EMPTY)
            return r;
    return -1;
}

void drop_piece(int col, int piece) {
    int r = get_open_row(col);
    if (r >= 0) {
        board[r][col] = piece;
        turn_count++;
    }
}

void drop_piece_animated(int col, int piece) {
    // In testing mode, just do a normal drop
    drop_piece(col, piece);
    prev_board[get_open_row(col) + 1][col] = piece; // sync prev_board
}

int check_win(int piece) {
    int r, c;
    for (r = 0; r < ROWS; r++)
        for (c = 0; c <= COLS - 4; c++)
            if (board[r][c] == piece && board[r][c+1] == piece &&
                board[r][c+2] == piece && board[r][c+3] == piece)
                return 1;
    for (c = 0; c < COLS; c++)
        for (r = 0; r <= ROWS - 4; r++)
            if (board[r][c] == piece && board[r+1][c] == piece &&
                board[r+2][c] == piece && board[r+3][c] == piece)
                return 1;
    for (r = 0; r <= ROWS - 4; r++)
        for (c = 0; c <= COLS - 4; c++)
            if (board[r][c] == piece && board[r+1][c+1] == piece &&
                board[r+2][c+2] == piece && board[r+3][c+3] == piece)
                return 1;
    for (r = 3; r < ROWS; r++)
        for (c = 0; c <= COLS - 4; c++)
            if (board[r][c] == piece && board[r-1][c+1] == piece &&
                board[r-2][c+2] == piece && board[r-3][c+3] == piece)
                return 1;
    return 0;
}

int is_board_full(void) {
    int c;
    for (c = 0; c < COLS; c++)
        if (board[0][c] == EMPTY)
            return 0;
    return 1;
}

void reset_game(void) {
    int r, c;
    for (r = 0; r < ROWS; r++)
        for (c = 0; c < COLS; c++) {
            board[r][c] = EMPTY;
            prev_board[r][c] = -1;
        }
    current_col = 3;
    game_over = 0;
    turn = PLAYER;
    prev_turn = -1;
    turn_count = 0;
    extended_key = 0;
    board_drawn = 0;
}

// AI (fully functional)

int evaluate_window(int window[4], int piece) {
    int opp = (piece == AI) ? PLAYER : AI;
    int count_piece = 0, count_opp = 0, count_empty = 0;
    int i;
    for (i = 0; i < 4; i++) {
        if (window[i] == piece) count_piece++;
        else if (window[i] == opp) count_opp++;
        else count_empty++;
    }
    if (count_piece == 4) return 100000;
    if (count_piece == 3 && count_empty == 1) return 50;
    if (count_piece == 2 && count_empty == 2) return 5;
    if (count_opp == 4) return -100000;
    if (count_opp == 3 && count_empty == 1) return -50;
    return 0;
}

int score_board(int piece) {
    int score = 0;
    int r, c, i;
    int window[4];
    for (r = 0; r < ROWS; r++)
        if (board[r][3] == piece)
            score += 3;
    for (r = 0; r < ROWS; r++) {
        for (c = 0; c <= COLS - 4; c++) {
            for (i = 0; i < 4; i++) window[i] = board[r][c + i];
            score += evaluate_window(window, piece);
        }
    }
    for (c = 0; c < COLS; c++) {
        for (r = 0; r <= ROWS - 4; r++) {
            for (i = 0; i < 4; i++) window[i] = board[r + i][c];
            score += evaluate_window(window, piece);
        }
    }
    for (r = 0; r <= ROWS - 4; r++) {
        for (c = 0; c <= COLS - 4; c++) {
            for (i = 0; i < 4; i++) window[i] = board[r + i][c + i];
            score += evaluate_window(window, piece);
        }
    }
    for (r = 3; r < ROWS; r++) {
        for (c = 0; c <= COLS - 4; c++) {
            for (i = 0; i < 4; i++) window[i] = board[r - i][c + i];
            score += evaluate_window(window, piece);
        }
    }
    return score;
}

static const int col_order[7] = {3, 2, 4, 1, 5, 0, 6};

int minimax(int depth, int alpha, int beta, int is_maximizing) {
    int ai_win = check_win(AI);
    int player_win = check_win(PLAYER);
    int full = is_board_full();
    if (ai_win) return 100000 + depth;
    if (player_win) return -100000 - depth;
    if (full) return 0;
    if (depth == 0) return score_board(AI);
    int i, col, row;
    if (is_maximizing) {
        int best = -9999999;
        for (i = 0; i < COLS; i++) {
            col = col_order[i];
            if (!is_valid_col(col)) continue;
            row = get_open_row(col);
            board[row][col] = AI;
            int val = minimax(depth - 1, alpha, beta, 0);
            board[row][col] = EMPTY;
            if (val > best) best = val;
            if (best > alpha) alpha = best;
            if (alpha >= beta) break;
        }
        return best;
    } else {
        int best = 9999999;
        for (i = 0; i < COLS; i++) {
            col = col_order[i];
            if (!is_valid_col(col)) continue;
            row = get_open_row(col);
            board[row][col] = PLAYER;
            int val = minimax(depth - 1, alpha, beta, 1);
            board[row][col] = EMPTY;
            if (val < best) best = val;
            if (best < beta) beta = best;
            if (alpha >= beta) break;
        }
        return best;
    }
}

int get_ai_move(void) {
    int best_col = 3;
    int best_score = -9999999;
    int i, col, row;
    for (i = 0; i < COLS; i++) {
        col = col_order[i];
        if (!is_valid_col(col)) continue;
        row = get_open_row(col);
        board[row][col] = AI;
        int val = minimax(MAX_DEPTH - 1, -9999999, 9999999, 0);
        board[row][col] = EMPTY;
        if (val > best_score) {
            best_score = val;
            best_col = col;
        }
    }
    return best_col;
}
